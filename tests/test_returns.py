"""1年リターン計算（crawler/returns.py）のテスト。投信総合検索ライブラリーにはアクセスしない。

  python tests/test_returns.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from crawler.returns import compute_return_1y, is_recent, one_year_before, parse_series  # noqa: E402
from datetime import date  # noqa: E402


def main():
    # 例：アジア半導体関連フォーカスF（2026-10-16時点）。前月末基準の公表値は +165.31% だったが、
    # 最新基準日では 11,748円 → 25,177円 で +114.31%（チャートと一致）
    pts = [("2025-10-20", 11748.0), ("2025-10-31", 12831.0), ("2026-09-30", 28262.0), ("2026-10-16", 25177.0)]
    assert compute_return_1y(pts) == (114.31, "2025-10-20", "2026-10-16")

    # 1年前の同日以前で最も新しい価格を起点にする（同日が休日なら直前の営業日）
    pts = [("2025-10-10", 100.0), ("2025-10-15", 110.0), ("2025-10-17", 999.0), ("2026-10-16", 132.0)]
    assert compute_return_1y(pts) == (20.0, "2025-10-15", "2026-10-16")

    # データが1年前より後から始まる場合：7日以内のずれなら最初の価格、それより短ければ計算しない（設定1年未満など）
    assert compute_return_1y([("2025-10-22", 100.0), ("2026-10-16", 150.0)]) == (50.0, "2025-10-22", "2026-10-16")
    assert compute_return_1y([("2026-03-01", 100.0), ("2026-10-16", 150.0)]) is None

    # 分配金を出すファンドは分配金再投資基準価額で計算する（呼び出し側で渡す系列）。並び順が乱れていても正しく計算
    assert compute_return_1y([("2026-10-16", 90.0), ("2025-10-16", 100.0)]) == (-10.0, "2025-10-16", "2026-10-16")

    # 価格が欠けている・0の点は無視、点が足りなければ計算しない
    assert compute_return_1y([("2025-10-16", 0.0), ("2026-10-16", 100.0)]) is None
    assert compute_return_1y([]) is None

    # うるう日の1年前は2月28日
    assert one_year_before(date(2028, 2, 29)) == date(2027, 2, 28)

    # チャートAPIの形式の変換
    assert parse_series([["2026/10/16", "25177.0"], ["2026/10/15", ""], None]) == [("2026-10-16", 25177.0)]

    # 最新日が基準日から古すぎる場合（チャートデータの更新停止）は使わない
    assert is_recent("2026-10-16", "2026-10-18") and not is_recent("2026-09-01", "2026-10-18")

    print("OK: 1年リターンの計算ルールはすべて期待どおりです")


if __name__ == "__main__":
    main()
